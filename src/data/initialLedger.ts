/**
 * Creates a new SalesTransaction record from a confirmed OrderDetails
 */
export function buildSalesTransactionFromOrder(order: OrderDetails): SalesTransaction {
  const isDelivered = order.status === 'delivered' || order.status === 'Livrée';
  const isCancelled = order.status === 'Annulée' || order.status === 'cancelled';

  const paymentStatus = isDelivered
    ? 'ENCAISSÉ'
    : isCancelled
    ? 'ANNULÉE'
    : 'EN_ATTENTE_LIVRAISON';

  return {
    transactionId: `TX-${order.orderId}`,
    orderId: order.orderId,
    timestamp: new Date().toISOString(),
    client: {
      name: order.customerName,
      phone: order.phone,
      governorate: order.governorate,
      address: order.address,
    },
    items: order.items.map((item) => ({
      productId: item.product.id,
      name: item.product.name,
      color: item.selectedColor.name,
      size: item.selectedSize,
      qty: item.quantity,
      unitPrice: item.product.price,
    })),
    subtotal: order.subtotal,
    shippingFee: order.shipping || 8,
    discountAmount: order.discountAmount || 0,
    promoCode: order.appliedCouponCode,
    bundleOffer: order.appliedBundleName,
    totalAmount: order.total,
    paymentStatus,
    orderStatus: order.status || 'Commande reçue',
  };
}

